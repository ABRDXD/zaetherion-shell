#!/usr/bin/env python3
"""Keep a real qmldir in every qs.* module folder, with the lines Quickshell would synthesize for it.

Quickshell (src/core/scan.cpp, 4f508be) synthesizes `module qs.<dir>` plus one line per Uppercase
.qml file, sorted ignoring case, with `internal` for `//@ pragma Internal` and `singleton` for
`pragma Singleton` in the header (the lines before the first `{`). A real qmldir switches that off
for its folder, so the files here must match it. They exist so Qt's QML disk cache can apply once
Quickshell loads such folders by file:// (quickshell-mirror/quickshell #1434, docs/COLDSTART.md).
The root keeps no qmldir: shell.qml stays on qs:.

    python3 tools/make_qmldirs.py           write them (after adding, renaming or removing a .qml)
    python3 tools/make_qmldirs.py --check   exit 1 if any is missing, stale or edited
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "# Generated by tools/make_qmldirs.py to match Quickshell's synthesized qmldir; do not edit."
SKIP = {".git", "__pycache__", "fixtures"}  # test fixtures are not part of the shell tree


def header_flags(qml: Path) -> str:
    internal = singleton = False
    for line in qml.read_text(errors="replace").splitlines():
        line = line.strip()
        if line == "pragma Singleton":
            singleton = True
        elif line.startswith("import"):
            continue
        elif line == "//@ pragma Internal":
            internal = True
        elif "{" in line:
            break
    return ("internal " if internal else "") + ("singleton " if singleton else "")


def expected(root: Path = ROOT) -> dict[Path, str]:
    """qmldir path → text, for every folder below the root that holds .qml files."""
    folders = {p.parent for p in root.rglob("*.qml") if not SKIP & set(p.relative_to(root).parts)}
    result = {}
    for folder in sorted(folders - {root}):
        module = folder.relative_to(root).as_posix().replace("/", ".")
        if not re.fullmatch(r"[A-Za-z0-9_.]+", module):
            continue
        lines = [HEADER, f"module qs.{module}"]
        for qml in sorted(folder.glob("*.qml"), key=lambda p: p.name.lower()):
            if qml.name[0].isupper():
                lines.append(f"{header_flags(qml)}{qml.stem} 1.0 {qml.name}")
        result[folder / "qmldir"] = "\n".join(lines) + "\n"
    return result


def generated(root: Path = ROOT) -> list[Path]:
    """The qmldir files on disk that this tool wrote (others are never touched)."""
    return [p for p in root.rglob("qmldir") if not SKIP & set(p.relative_to(root).parts)
            and p.read_text(errors="replace").startswith(HEADER)]


def problems(root: Path = ROOT) -> list[str]:
    want = expected(root)
    found = [f"{p.relative_to(root)}: missing" if not p.exists() else f"{p.relative_to(root)}: out of date"
             for p, text in want.items() if not p.exists() or p.read_text() != text]
    found += [f"{p.relative_to(root)}: no .qml left" for p in generated(root) if p not in want]
    return found


def write(root: Path = ROOT) -> list[Path]:
    want = expected(root)
    for stale in generated(root):
        if stale not in want:
            stale.unlink()
    changed = [p for p, text in want.items() if not p.exists() or p.read_text() != text]
    for path in changed:
        path.write_text(want[path])
    return changed


def main(argv: list[str]) -> int:
    check = "--check" in argv
    rest = [a for a in argv if a != "--check"]
    root = Path(rest[0]).resolve() if rest else ROOT
    if check:
        for line in (found := problems(root)):
            print(line)
        return 1 if found else 0
    for path in write(root):
        print(path.relative_to(root))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
