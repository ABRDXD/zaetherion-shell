#!/usr/bin/env python3
"""The C++ core's op table (Z226): every op's argument signature and every topic, read from the Python core's own
registry, so fartd-cpp binds arguments exactly as `inspect.signature(handler).bind(client, **args)` does
(bad-args vs unknown-op, the first missing or unexpected name) for ops it hasn't ported yet as well.

    tools/cpp_op_table.py            write core-cpp/src/op_table.inc
    tools/cpp_op_table.py --check    exit 1 if the checked-in table differs from the Python core's registry

The table is JSON inside a C++ raw string: {"ops": [{"op", "peer", "params": [{"name", "default"?}], "varkw"}],
"topics": [...]} in registration order (the order the core's bad-args message lists topics in). A param without
"default" is required. Defaults are the Python literals as JSON.
"""
from __future__ import annotations

import argparse
import asyncio
import inspect
import json
from pathlib import Path
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
TABLE = ROOT / "core-cpp/src/op_table.inc"
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))


def _core(state: Path):
    from core.app import Core
    from core.guards import SessionGuard
    import core_fakes

    clock, scheduler, _, host = core_fakes.fakes()

    async def spawn():
        raise OSError("no view here")
    return Core(clock, scheduler, host, state, spawn=spawn, guard_types=[SessionGuard])


def _param(p: inspect.Parameter) -> dict:
    entry = {"name": p.name}
    if p.default is not inspect.Parameter.empty:
        json.dumps(p.default)  # a default the table can't carry would be a new kind of op: fail loudly
        entry["default"] = p.default
    return entry


def build() -> dict:
    async def collect():
        with tempfile.TemporaryDirectory(prefix="op-table-") as temp:
            core = _core(Path(temp) / "state")
            ops = []
            for name, handler in core.server.ops.items():
                params = list(inspect.signature(handler).parameters.values())
                peer, rest = params[0], params[1:]
                if peer.kind not in (peer.POSITIONAL_ONLY, peer.POSITIONAL_OR_KEYWORD):
                    raise SystemExit(f"{name}: first parameter {peer.name} is not the peer")
                varkw = None
                named = []
                for p in rest:
                    if p.kind is p.VAR_KEYWORD:
                        varkw = p.name
                    elif p.kind is p.POSITIONAL_OR_KEYWORD:
                        named.append(_param(p))
                    else:  # *args, positional-only (never fillable) or keyword-only (bind words its error otherwise)
                        raise SystemExit(f"{name}: parameter {p.name} has kind {p.kind}")
                ops.append({"op": name, "peer": peer.name, "params": named, "varkw": varkw})
            topics = list(core.server.snapshots)
            await core.close()
            return {"ops": ops, "topics": topics}
    return asyncio.run(collect())


def render(table: dict) -> str:
    line = lambda value: json.dumps(value, separators=(",", ":"), ensure_ascii=True)  # noqa: E731
    ops = ",\n  ".join(line(op) for op in table["ops"])
    body = f'{{\n "ops": [\n  {ops}\n ],\n "topics": {line(table["topics"])}\n}}'
    return ("// Generated by tools/cpp_op_table.py from the Python core's registry (core/app.py, core/protocol.py).\n"
            "// Do not edit: rerun the tool when an op or topic changes. tests/test_cpp_core.py checks it is current.\n"
            f'R"optable({body})optable"\n')


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    table = build()
    text = render(table)
    if args.check:
        if not TABLE.exists() or TABLE.read_text() != text:
            print(f"{TABLE.relative_to(ROOT)} differs from the Python core's registry; rerun without --check")
            return 1
        print(f"op table matches ({len(table['ops'])} ops, {len(table['topics'])} topics)")
        return 0
    TABLE.parent.mkdir(parents=True, exist_ok=True)
    TABLE.write_text(text)
    print(f"wrote {TABLE.relative_to(ROOT)} ({len(table['ops'])} ops, {len(table['topics'])} topics)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
